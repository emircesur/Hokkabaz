//! Writes `docs/N8N_COVERAGE.md` content to stdout: which of the popular n8n node types
//! (`docs/n8n-popular-nodes.txt`, ranked) the registry supports.
//! `cargo run -p hk-ffi --example coverage > docs/N8N_COVERAGE.md`
#![allow(clippy::print_stdout)]

fn full(t: &str) -> String {
    match t.strip_prefix("lc:") {
        Some(rest) => format!("@n8n/n8n-nodes-langchain.{rest}"),
        None => format!("n8n-nodes-base.{t}"),
    }
}

fn main() {
    let reg = hk_ffi::nodes::registry();
    let list = std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/n8n-popular-nodes.txt")).expect("popular list");
    let ranked: Vec<&str> = list.lines().map(str::trim).filter(|l| !l.is_empty() && !l.starts_with('#')).collect();
    let aliases = [("s3", "awsS3"), ("function", "function"), ("start", "start")];
    let supported = |t: &str| reg.latest(&full(t)).is_some() || aliases.iter().any(|(a, b)| *a == t && reg.latest(&full(b)).is_some());
    let have: Vec<&&str> = ranked.iter().filter(|t| supported(t)).collect();
    let missing: Vec<(usize, &&str)> = ranked.iter().enumerate().filter(|(_, t)| !supported(t)).map(|(i, t)| (i + 1, t)).collect();
    let pct = 100.0 * have.len() as f64 / ranked.len() as f64;
    println!("# n8n node coverage\n");
    println!("Generated by `cargo run -p hk-ffi --example coverage`. Ranking source: `docs/n8n-popular-nodes.txt`.\n");
    println!("**{} of {} ranked node types supported ({pct:.0}%).** Registry total: {} node types.\n", have.len(), ranked.len(), reg.types().count());
    println!("Unsupported nodes in imported workflows still open and round-trip intact; they run on a configured n8n instance (remote delegation, `docs/N8N_SYNC.md`).\n");
    println!("## Missing, by popularity rank\n\n| Rank | Node type |\n|---|---|");
    for (rank, t) in missing {
        println!("| {rank} | `{}` |", full(t));
    }
    println!("\n## Supported\n");
    for t in have {
        println!("- `{}`", full(t));
    }
}
